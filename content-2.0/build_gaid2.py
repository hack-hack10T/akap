def module_html(num, title, question, items, add=None):
    parts = [f'<section data-module="{num}"><h2>{num}. {title}</h2><p class="q">{question}</p>']
    fixes_log = []
    for pref, tag in items:
        t = find(pref)
        if t is None or not t.strip():
            continue
        if tag:
            t, fl = apply_fixes(t, tag)
            fixes_log += fl
        t = clean(t)
        parts.append(f'<h3>{H.escape(pref)}</h3><p>{t}</p>')
    if add:
        parts.append(add)
    parts.append('</section>')
    return '\n'.join(parts), fixes_log

