import json, re, html as H

ch = json.load(open('/tmp/chapters.json'))
def find(pref):
    for k in ch:
        if k.startswith(pref):
            return ch[k]
    return ''

def clean(t):
    t = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', t)          # markdown bold
    t = re.sub(r'\[ \]', '', t)                              # чекбоксы
    t = re.sub(r'^\s*\|.*?\|.*?$', '', t, flags=re.M)        # строки таблиц
    t = re.sub(r'^\s*:?-{3,}:?\s*$', '', t, flags=re.M)      # разделители
    t = t.replace('|', ' · ')
    t = re.sub(r'(?<!\*)\*(?!\*)', '', t)                    # одиночные звёздочки
    t = re.sub(r'\s+', ' ', t).strip()
    return t

